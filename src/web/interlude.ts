function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

export function interlude(t: { y: number; m: number; w: number }, slot: string): string[] {
  const special = MONTHLY[t.m]?.[slot] ?? [];
  const general = GENERAL[slot] ?? GENERAL['방과후'];
  const h = hash(`${t.y}.${t.m}.${t.w}.${slot}`);
  // 그 달의 첫 주에는 달 장면을 먼저, 그 뒤로는 섞는다
  if (special.length && (t.w === 1 || h % 3 === 0)) return special[h % special.length];
  return general[h % general.length];
}
